const perPage = 18

function getGenreNames(genreIds = []) {
  return genreIds.map((id) => genreMap.get(id)).filter(Boolean)
}

function sortMovies(movies, sort) {
  const sorted = [...movies]
  if (sort === 'rating_desc') {
    return sorted.sort((a, b) => b.vote_average - a.vote_average)
  }
  if (sort === 'rating_asc') {
    return sorted.sort((a, b) => a.vote_average - b.vote_average)
  }
  if (sort === 'year_desc') {
    return sorted.sort((a, b) => b.release_date.localeCompare(a.release_date))
  }
  if (sort === 'year_asc') {
    return sorted.sort((a, b) => a.release_date.localeCompare(b.release_date))
  }
  if (sort === 'title_asc') {
    return sorted.sort((a, b) => a.title.localeCompare(b.title, 'uk'))
  }
  if (sort === 'title_desc') {
    return sorted.sort((a, b) => b.title.localeCompare(a.title, 'uk'))
  }
  return sorted.sort((a, b) => b.popularity - a.popularity)
}

export function queryDemoMovies({
  page = 1,
  genreId,
  year,
  minRating,
  sort = 'popularity_desc',
  query = '',
}) {
  const normalizedQuery = String(query || '').trim().toLowerCase()
  const normalizedGenre = Number(genreId) || null
  const normalizedYear = Number(year) || null
  const normalizedRating = Number(minRating) || 0

  const filtered = demoMovies.filter((movie) => {
    if (
      normalizedQuery &&
      !movie.title.toLowerCase().includes(normalizedQuery) &&
      !movie.original_title.toLowerCase().includes(normalizedQuery)
    ) {
      return false
    }
    if (normalizedGenre && !movie.genre_ids.includes(normalizedGenre)) {
      return false
    }
    if (
      normalizedYear &&
      !movie.release_date.startsWith(String(normalizedYear))
    ) {
      return false
    }
    if (movie.vote_average < normalizedRating) return false
    return true
  })

  const sorted = sortMovies(filtered, sort)
  const totalResults = sorted.length
  const totalPages = Math.max(1, Math.ceil(totalResults / perPage))
  const currentPage = Math.min(Math.max(Number(page) || 1, 1), totalPages)
  const start = (currentPage - 1) * perPage
  const results = sorted.slice(start, start + perPage).map((movie) => ({
    ...movie,
    genres: getGenreNames(movie.genre_ids),
  }))

  return {
    page: currentPage,
    totalPages,
    totalResults,
    results,
  }
}

export function getDemoMovie(id) {
  const movie = demoMovies.find((item) => item.id === Number(id))
  if (!movie) return null
  return {
    ...movie,
    genres: getGenreNames(movie.genre_ids),
  }
}
